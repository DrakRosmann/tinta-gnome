#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    PlatformIO,
    Arduino,
    /// A Cargo project for a bare-metal target.
    Cargo,
    PicoSdk,
    EspIdf,
    Zephyr,
    /// Generated by STM32CubeMX (a `.ioc` file), built with its Makefile or CMake.
    Stm32Cube,
    /// A Makefile or CMake with a cross compiler, or anything `.tinta/embedded.json` describes.
    Firmware,
}

impl Kind {
    pub fn label(self) -> &'static str {
        match self {
            Kind::PlatformIO => "PlatformIO",
            Kind::Arduino => "Arduino",
            Kind::Cargo => "Rust",
            Kind::PicoSdk => "Pico SDK",
            Kind::EspIdf => "ESP-IDF",
            Kind::Zephyr => "Zephyr",
            Kind::Stm32Cube => "STM32Cube",
            Kind::Firmware => "Firmware",
        }
    }
}

/// What puts the firmware on the board, and what debugs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Probe {
    ProbeRs,
    OpenOcd,
    /// The open source stlink tools: st-flash, st-util.
    StLink,
    /// ST's STM32CubeProgrammer.
    Stm32Programmer,
    JLink,
    PyOcd,
    /// A Raspberry Pi Pico over USB.
    Picotool,
    /// Copying a .uf2 to the drive a board shows in its bootloader.
    Uf2,
}

impl Probe {
    pub fn parse(s: &str) -> Option<Probe> {
        Some(match s.to_ascii_lowercase().replace(['_', ' '], "-").as_str() {
            "probe-rs" | "probers" => Probe::ProbeRs,
            "openocd" => Probe::OpenOcd,
            "stlink" | "st-link" | "st-flash" | "st-util" | "stutil" => Probe::StLink,
            "stm32programmer" | "stm32cubeprogrammer" | "stm32-programmer-cli" | "cubeprogrammer" => Probe::Stm32Programmer,
            "jlink" | "j-link" | "segger" => Probe::JLink,
            "pyocd" => Probe::PyOcd,
            "picotool" => Probe::Picotool,
            "uf2" => Probe::Uf2,
            _ => return None,
        })
    }

    /// The program that flashes with it.
    pub fn tool(self) -> &'static str {
        match self {
            Probe::ProbeRs => "probe-rs",
            Probe::OpenOcd => "openocd",
            Probe::StLink => "st-flash",
            Probe::Stm32Programmer => "STM32_Programmer_CLI",
            Probe::JLink => "JLinkExe",
            Probe::PyOcd => "pyocd",
            Probe::Picotool => "picotool",
            Probe::Uf2 => "cp",
        }
    }
}

/// `.tinta/embedded.json`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Deserialize)]
#[serde(default, rename_all = "camelCase")]
pub struct Config {
    pub board: Option<String>,
    pub chip: Option<String>,
    pub port: Option<String>,
    pub baud: Option<u32>,
    pub probe: Option<String>,
    pub openocd: Vec<String>,
    pub firmware: Option<String>,
    pub build: Option<String>,
    pub flash: Option<String>,
    pub monitor: Option<String>,
    pub clean: Option<String>,
}

pub fn load_config(root: &Path) -> Result<Option<Config>, String> {
    let Ok(src) = std::fs::read_to_string(root.join(CONFIG_PATH)) else { return Ok(None) };
    serde_json::from_str(&crate::settings::strip_jsonc(&src)).map(Some).map_err(|e| format!("{CONFIG_PATH}: {e}"))
}

/// What the user chose in the editor for a project: kept on this computer, not in the project.
pub mod prefs {
    use serde::{Deserialize, Serialize};
    use std::collections::HashMap;
    use std::path::{Path, PathBuf};

    #[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
    #[serde(default)]
    pub struct Prefs {
        pub port: Option<String>,
        pub baud: Option<u32>,
        pub board: Option<String>,
    }

    fn store() -> PathBuf {
        crate::settings::state_dir().join("embedded.json")
    }

    fn load_all() -> HashMap<String, Prefs> {
        std::fs::read_to_string(store()).ok().and_then(|s| serde_json::from_str(&s).ok()).unwrap_or_default()
    }

    pub fn load(root: &Path) -> Prefs {
        load_all().remove(&root.to_string_lossy().into_owned()).unwrap_or_default()
    }

    pub fn save(root: &Path, prefs: &Prefs) -> Result<(), String> {
        let mut all = load_all();
        if *prefs == Prefs::default() {
            all.remove(&root.to_string_lossy().into_owned());
        } else {
            all.insert(root.to_string_lossy().into_owned(), prefs.clone());
        }
        let p = store();
        if let Some(d) = p.parent() {
            std::fs::create_dir_all(d).map_err(|e| e.to_string())?;
        }
        std::fs::write(p, serde_json::to_string_pretty(&all).map_err(|e| e.to_string())?).map_err(|e| e.to_string())
    }
}


    /// The monitor against a pseudo-terminal standing in for the board: what the board says shows
    /// up, and a line typed gets to the board.
    #[test]
    fn serial_monitor_talks_to_the_port() {
        use std::io::{Read, Write};
        use std::os::fd::AsRawFd;
        let board = crate::dap::open_tty().unwrap();
        let port = board.path.to_string_lossy().into_owned();
        let cmd = serial_monitor(Some(&port), 9600, false);
        use std::os::unix::process::CommandExt;
        let mut child = std::process::Command::new("sh")
            .args(["-c", &cmd])
            .process_group(0)
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::null())
            .spawn()
            .unwrap();
        let mut master = std::fs::File::from(board.master.try_clone().unwrap());
        // Nonblocking reads from the board's side.
        unsafe {
            let fd = master.as_raw_fd();
            libc::fcntl(fd, libc::F_SETFL, libc::fcntl(fd, libc::F_GETFL) | libc::O_NONBLOCK);
        }
        std::thread::sleep(std::time::Duration::from_millis(600));
        master.write_all(b"temperatura: 21\r\n").unwrap();
        child.stdin.as_mut().unwrap().write_all(b"led on\n").unwrap();
        let mut got = Vec::new();
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(5);
        while std::time::Instant::now() < deadline && !String::from_utf8_lossy(&got).contains("led on") {
            let mut buf = [0u8; 256];
            if let Ok(n) = master.read(&mut buf) {
                got.extend_from_slice(&buf[..n]);
            }
            std::thread::sleep(std::time::Duration::from_millis(50));
        }
        assert!(String::from_utf8_lossy(&got).contains("led on"), "the board got {:?}", String::from_utf8_lossy(&got));
        unsafe {
            // As Ctrl+C in a terminal: to the whole foreground group.
            libc::kill(-(child.id() as i32), libc::SIGINT);
        }
        let mut out = String::new();
        let mut stdout = child.stdout.take().unwrap();
        let waited = std::thread::spawn(move || {
            let _ = stdout.read_to_string(&mut out);
            out
        });
        let status = child.wait().unwrap();
        let out = waited.join().unwrap();
        assert!(out.contains("Serial monitor: ") && out.contains("temperatura: 21"), "{out}");
        assert!(status.success(), "Ctrl+C ends it cleanly: {status:?}");
    }

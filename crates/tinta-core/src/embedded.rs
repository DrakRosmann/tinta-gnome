//! Microcontrollers: what kind of firmware project a folder is, how to build it, put it on the
//! board, talk to the board over a serial port, and debug it through a probe.
//!
//! The project's files say most of it: `platformio.ini`, an Arduino sketch, a Cargo project for a
//! bare-metal target, the Pico SDK, ESP-IDF, Zephyr, a project from STM32CubeMX, or a Makefile or
//! CMake that uses a cross compiler. `.tinta/embedded.json` fills in what they can't say, like the
//! chip or the probe, and what the user chose in the editor (the serial port, the speed, the
//! board) is kept apart from the project, for this computer only.


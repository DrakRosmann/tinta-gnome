/// The project at `root`, if it's a firmware project. `use_project_file` says whether the folder
/// may use its own `.tinta/embedded.json`.
pub fn detect(root: &Path, use_project_file: bool) -> Result<Option<Project>, String> {
    let config = if use_project_file { load_config(root)? } else { None };
    Ok(detect_with(root, config, &prefs::load(root)))
}

fn read(root: &Path, f: &str) -> Option<String> {
    std::fs::read_to_string(root.join(f)).ok()
}

fn files_with_ext(dir: &Path, ext: &str) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.extension().is_some_and(|e| e.eq_ignore_ascii_case(ext)))
        .collect();
    out.sort();
    out
}

pub fn detect_with(root: &Path, config: Option<Config>, prefs: &prefs::Prefs) -> Option<Project> {
    let has_config = config.is_some();
    let config = config.unwrap_or_default();
    let mut p = Project {
        kind: Kind::Firmware,
        root: root.to_path_buf(),
        board: None,
        boards: Vec::new(),
        chip: None,
        target: None,
        runner: None,
        probe: config.probe.as_deref().and_then(Probe::parse),
        openocd: config.openocd.clone(),
        port: None,
        baud: 0,
        config: config.clone(),
        pio_board: None,
        debug_tool: None,
    };
    let mut default_baud = DEFAULT_BAUD;
    let cmake = read(root, "CMakeLists.txt").unwrap_or_default();
    if let Some(ini) = read(root, "platformio.ini") {
        p.kind = Kind::PlatformIO;
        let pio = parse_platformio(&ini);
        p.boards = pio.envs.iter().map(|e| e.name.clone()).collect();
        let wanted = |b: &Option<String>| b.clone().filter(|b| p.boards.contains(b));
        let env_name = wanted(&prefs.board).or_else(|| wanted(&config.board)).or(pio.default_env.clone().filter(|e| p.boards.contains(e))).or_else(|| p.boards.first().cloned());
        if let Some(env) = env_name.as_ref().and_then(|n| pio.envs.iter().find(|e| &e.name == n)) {
            p.pio_board = env.board.clone();
            p.debug_tool = env.debug_tool.clone();
            p.port = env.monitor_port.clone().or(env.upload_port.clone());
            default_baud = env.monitor_speed.unwrap_or(9600);
        } else {
            default_baud = 9600;
        }
        p.board = env_name;
    } else if !files_with_ext(root, "ino").is_empty() {
        p.kind = Kind::Arduino;
        let yaml = read(root, "sketch.yaml").or_else(|| read(root, "sketch.yml")).unwrap_or_default();
        p.board = prefs.board.clone().or(config.board.clone()).or_else(|| yaml_value(&yaml, "default_fqbn"));
        p.port = yaml_value(&yaml, "default_port");
        default_baud = 9600;
    } else if root.join("Cargo.toml").exists() && let Some(cargo) = cargo_config(root) {
        p.kind = Kind::Cargo;
        p.chip = cargo.chip;
        p.target = cargo.target;
        p.runner = cargo.runner;
    } else if cmake.contains("pico_sdk_init") || cmake.contains("pico_sdk_import") {
        p.kind = Kind::PicoSdk;
        p.boards = PICO_BOARDS.iter().map(|b| b.to_string()).collect();
        p.board = prefs.board.clone().or(config.board.clone()).or_else(|| cmake_set(&cmake, "PICO_BOARD"));
        p.chip = Some(if p.board.as_deref().is_some_and(|b| b.starts_with("pico2")) { "RP2350" } else { "RP2040" }.to_string());
    } else if (cmake.contains("project.cmake") && cmake.contains("IDF_PATH")) || root.join("sdkconfig").exists() || root.join("sdkconfig.defaults").exists() {
        p.kind = Kind::EspIdf;
    } else if cmake.contains("find_package(Zephyr") {
        p.kind = Kind::Zephyr;
        p.board = prefs.board.clone().or(config.board.clone()).or_else(|| cmake_set(&cmake, "BOARD"));
    } else if let Some(ioc) = files_with_ext(root, "ioc").first() {
        p.kind = Kind::Stm32Cube;
        p.chip = std::fs::read_to_string(ioc).ok().and_then(|s| ioc_chip(&s));
    } else if cross_compiled(root) || has_config {
        p.kind = Kind::Firmware;
        p.board = config.board.clone();
    } else {
        return None;
    }
    if p.kind == Kind::PicoSdk && let Some(b) = prefs.board.clone() {
        p.board = Some(b);
    }
    if let Some(c) = &config.chip {
        p.chip = Some(c.clone());
    }
    p.port = prefs.port.clone().or(config.port.clone()).or(p.port);
    p.baud = prefs.baud.or(config.baud).unwrap_or(default_baud);
    Some(p)
}

/// A Makefile or CMake that builds with a compiler for microcontrollers.
fn cross_compiled(root: &Path) -> bool {
    const MARKS: &[&str] = &["arm-none-eabi", "riscv32-unknown-elf", "riscv64-unknown-elf", "riscv-none-elf", "avr-gcc", "xtensa-"];
    let mut sources: Vec<String> = ["Makefile", "makefile", "GNUmakefile", "CMakeLists.txt", "CMakePresets.json"].iter().filter_map(|f| read(root, f)).collect();
    for dir in [root.to_path_buf(), root.join("cmake")] {
        sources.extend(files_with_ext(&dir, "cmake").iter().filter_map(|f| std::fs::read_to_string(f).ok()));
    }
    sources.iter().any(|s| MARKS.iter().any(|m| s.contains(m)))
}

pub const PICO_BOARDS: &[&str] = &["pico", "pico_w", "pico2", "pico2_w"];

#[derive(Debug, Default, Clone, PartialEq, Eq)]
struct PioEnv {
    name: String,
    board: Option<String>,
    upload_port: Option<String>,
    monitor_port: Option<String>,
    monitor_speed: Option<u32>,
    debug_tool: Option<String>,
}

#[derive(Debug, Default)]
struct Pio {
    envs: Vec<PioEnv>,
    default_env: Option<String>,
}

fn parse_platformio(src: &str) -> Pio {
    let mut out = Pio::default();
    let mut common = PioEnv::default();
    let mut section = String::new();
    for raw in src.lines() {
        // Continuation lines of a list start with spaces; only the first value matters here.
        if raw.starts_with([' ', '\t']) {
            continue;
        }
        let line = raw.split([';', '#']).next().unwrap_or("").trim();
        if let Some(s) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            section = s.trim().to_string();
            if let Some(name) = section.strip_prefix("env:") {
                out.envs.push(PioEnv { name: name.trim().to_string(), ..common.clone() });
            }
            continue;
        }
        let Some((k, v)) = line.split_once('=') else { continue };
        let (k, v) = (k.trim(), v.trim().to_string());
        if section == "platformio" && k == "default_envs" {
            out.default_env = v.split(',').map(str::trim).find(|s| !s.is_empty()).map(str::to_string);
            continue;
        }
        let env = if section == "env" {
            &mut common
        } else if section.starts_with("env:") {
            match out.envs.last_mut() {
                Some(e) => e,
                None => continue,
            }
        } else {
            continue;
        };
        let value = (!v.is_empty()).then(|| v.clone());
        match k {
            "board" => env.board = value,
            "upload_port" => env.upload_port = value,
            "monitor_port" => env.monitor_port = value,
            "monitor_speed" => env.monitor_speed = v.parse().ok(),
            "debug_tool" => env.debug_tool = value,
            _ => {}
        }
    }
    out
}

/// `key: value` at the top of a YAML file, as `sketch.yaml` has them.
fn yaml_value(src: &str, key: &str) -> Option<String> {
    src.lines().find_map(|l| {
        let (k, v) = l.split_once(':')?;
        (k.trim() == key && !l.starts_with([' ', '\t'])).then(|| v.trim().trim_matches(['"', '\'']).to_string()).filter(|v| !v.is_empty())
    })
}

/// `set(NAME value)` in a CMakeLists.txt.
fn cmake_set(src: &str, name: &str) -> Option<String> {
    src.lines().find_map(|l| {
        let l = l.trim();
        let inner = l.strip_prefix("set(").or_else(|| l.strip_prefix("set ("))?.trim_end().strip_suffix(')')?;
        let mut words = inner.split_whitespace();
        (words.next()? == name).then(|| words.next().map(|w| w.trim_matches('"').to_string())).flatten()
    })
}

/// The first word inside `name(...)` in a CMakeLists.txt.
fn cmake_call(src: &str, name: &str) -> Option<String> {
    src.lines().find_map(|l| {
        let rest = l.trim().strip_prefix(name)?.trim_start().strip_prefix('(')?;
        rest.split([' ', ')', '\t']).find(|w| !w.is_empty()).map(|w| w.trim_matches('"').to_string()).filter(|w| !w.starts_with('$'))
    })
}

/// The chip of a CubeMX project, as probe-rs names it: `STM32F103C8Tx` → `STM32F103C8`.
fn ioc_chip(src: &str) -> Option<String> {
    let value = |key: &str| src.lines().find_map(|l| l.strip_prefix(key).map(|v| v.trim().to_string())).filter(|v| !v.is_empty());
    let name = value("Mcu.UserName=").or_else(|| value("Mcu.CPN="))?;
    Some(stm32_part(&name))
}

/// An STM32's part number without the package and temperature letters, which the tools don't
/// all know: `STM32F411CEUx` → `STM32F411CE`.
pub fn stm32_part(name: &str) -> String {
    let up = name.to_ascii_uppercase();
    if up.starts_with("STM32") && up.len() > 11 { up[..11].to_string() } else { up }
}

fn is_stm32(chip: Option<&str>) -> bool {
    chip.is_some_and(|c| c.to_ascii_uppercase().starts_with("STM32"))
}

/// OpenOCD's target file for an STM32: `STM32F103C8` → `target/stm32f1x.cfg`.
pub fn stm32_openocd_target(chip: &str) -> Option<String> {
    let up = chip.to_ascii_uppercase();
    let rest = up.strip_prefix("STM32")?;
    let fam: String = rest.chars().take(2).collect();
    (fam.len() == 2 && fam.chars().next()?.is_ascii_alphabetic()).then(|| format!("target/stm32{}x.cfg", fam.to_ascii_lowercase()))
}

struct CargoEmbedded {
    target: Option<String>,
    runner: Option<String>,
    chip: Option<String>,
}

/// Rust targets with no operating system under them.
fn bare_metal_target(t: &str) -> bool {
    t.starts_with("thumb") || t.starts_with("xtensa") || t.starts_with("avr") || t.contains("-none") || (t.starts_with("riscv32") && !t.contains("linux"))
}

/// A string, or an array of strings joined, from a TOML value.
fn toml_value(v: &str) -> Option<String> {
    let v = v.trim();
    if let Some(inner) = v.strip_prefix('[') {
        let words: Vec<String> = inner.trim_end_matches(']').split(',').map(|w| w.trim().trim_matches(['"', '\'']).to_string()).filter(|w| !w.is_empty()).collect();
        return (!words.is_empty()).then(|| words.join(" "));
    }
    let v = v.split(" #").next().unwrap_or(v).trim();
    Some(v.trim_matches(['"', '\'']).to_string()).filter(|s| !s.is_empty())
}

fn cargo_config(root: &Path) -> Option<CargoEmbedded> {
    let src = read(root, ".cargo/config.toml").or_else(|| read(root, ".cargo/config")).unwrap_or_default();
    let (mut target, mut runner) = (None, None);
    let mut section = String::new();
    for line in src.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            section = line.trim_matches(['[', ']']).trim().to_string();
            continue;
        }
        let Some((k, v)) = line.split_once('=') else { continue };
        match (section.as_str(), k.trim()) {
            ("build", "target") => target = toml_value(v),
            (s, "runner") if s.starts_with("target.") && runner.is_none() => runner = toml_value(v),
            _ => {}
        }
    }
    let embed = read(root, "Embed.toml").unwrap_or_default();
    let flashing = runner.as_deref().is_some_and(|r| ["probe-rs", "elf2uf2", "espflash", "picotool", "cargo-embed", "ravedude", "qemu-system-arm"].iter().any(|t| r.contains(t)));
    let bare = target.as_deref().is_some_and(bare_metal_target);
    if !bare && !flashing && !root.join("memory.x").exists() && embed.is_empty() {
        return None;
    }
    let chip = runner.as_deref().and_then(chip_in_command).or_else(|| embed.lines().find_map(|l| {
        let (k, v) = l.split_once('=')?;
        (k.trim() == "chip").then(|| toml_value(v)).flatten()
    }));
    Some(CargoEmbedded { target, runner, chip })
}

/// `--chip X` in a command.
fn chip_in_command(cmd: &str) -> Option<String> {
    let mut words = cmd.split_whitespace();
    while let Some(w) = words.next() {
        if w == "--chip" {
            return words.next().map(str::to_string);
        }
        if let Some(c) = w.strip_prefix("--chip=") {
            return Some(c.to_string());
        }
    }
    None
}

/// The package's name in a Cargo.toml.
fn cargo_package_name(src: &str) -> Option<String> {
    let mut in_package = false;
    for line in src.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if in_package && let Some((k, v)) = line.split_once('=') && k.trim() == "name" {
            return toml_value(v);
        }
    }
    None
}

/// PlatformIO's description of a board, from the platforms it installed.
pub fn pio_board_info(board: &str) -> Option<BoardInfo> {
    let base = dirs::home_dir()?.join(".platformio/platforms");
    for platform in std::fs::read_dir(base).ok()?.flatten() {
        let Ok(src) = std::fs::read_to_string(platform.path().join("boards").join(format!("{board}.json"))) else { continue };
        let Ok(v) = serde_json::from_str::<Value>(&src) else { continue };
        let s = |v: &Value| v.as_str().map(str::to_string);
        return Some(BoardInfo {
            mcu: s(&v["build"]["mcu"]),
            openocd_target: s(&v["debug"]["openocd_target"]),
            jlink_device: s(&v["debug"]["jlink_device"]),
            default_tool: v["debug"]["default_tools"].as_array().and_then(|a| a.first()).and_then(s),
        });
    }
    None
}

/// An ELF file, by its first bytes.
pub fn is_elf(p: &Path) -> bool {
    use std::io::Read;
    let mut magic = [0u8; 4];
    p.is_file() && std::fs::File::open(p).and_then(|mut f| f.read_exact(&mut magic)).is_ok() && &magic == b"\x7fELF"
}

/// The newest ELF in these folders, looking `depth` folders down. Only `.elf` files, or files
/// with no extension when `bare` (Cargo's).
fn newest_elf(dirs: &[PathBuf], depth: usize, bare: bool) -> Option<PathBuf> {
    fn walk(dir: &Path, depth: usize, bare: bool, best: &mut Option<(std::time::SystemTime, PathBuf)>) {
        let Ok(entries) = std::fs::read_dir(dir) else { return };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                if depth > 0 && !p.file_name().is_some_and(|n| n == "deps" || n == "CMakeFiles" || n == ".git") {
                    walk(&p, depth - 1, bare, best);
                }
                continue;
            }
            let ext = p.extension().and_then(|e| e.to_str()).map(str::to_ascii_lowercase);
            let wanted = match ext.as_deref() {
                Some("elf" | "axf" | "out") => true,
                None => bare,
                _ => false,
            };
            if !wanted || !is_elf(&p) {
                continue;
            }
            let Ok(time) = e.metadata().and_then(|m| m.modified()) else { continue };
            if best.as_ref().is_none_or(|(t, _)| time > *t) {
                *best = Some((time, p));
            }
        }
    }
    let mut best = None;
    for d in dirs {
        walk(d, depth, bare, &mut best);
    }
    best.map(|(_, p)| p)
}

/// Where a sketch is built: outside it, so nothing new appears among its files.
pub fn arduino_build_dir(root: &Path) -> PathBuf {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    root.hash(&mut h);
    let name = root.file_name().unwrap_or_default().to_string_lossy().into_owned();
    dirs::cache_dir().unwrap_or_else(std::env::temp_dir).join("tinta-gnome").join("arduino").join(format!("{name}-{:08x}", h.finish() as u32))
}

/// The ESP-IDF command, with its environment loaded when it isn't already.
fn idf(find: &dyn Fn(&str) -> bool) -> Result<String, Need> {
    if find("idf.py") {
        return Ok("idf.py".into());
    }
    let mut candidates: Vec<PathBuf> = std::env::var_os("IDF_PATH").map(PathBuf::from).into_iter().collect();
    if let Some(h) = dirs::home_dir() {
        candidates.push(h.join("esp/esp-idf"));
        if let Ok(list) = std::fs::read_dir(h.join(".espressif/frameworks")) {
            candidates.extend(list.flatten().map(|e| e.path()));
        }
    }
    candidates
        .into_iter()
        .map(|d| d.join("export.sh"))
        .find(|p| p.is_file())
        .map(|p| format!(". {} >/dev/null 2>&1 && idf.py", shell_quote(&p.to_string_lossy())))
        .ok_or_else(|| need_tool("idf.py"))
}

/// PlatformIO's command: on the PATH, or where its installer puts it.
fn pio(find: &dyn Fn(&str) -> bool) -> Result<String, Need> {
    if find("pio") {
        return Ok("pio".into());
    }
    if find("platformio") {
        return Ok("platformio".into());
    }
    dirs::home_dir()
        .map(|h| h.join(".platformio/penv/bin/pio"))
        .filter(|p| p.is_file())
        .map(|p| shell_quote(&p.to_string_lossy()))
        .ok_or_else(|| need_tool("pio"))
}

/// Zephyr's `west`: on the PATH, or in the virtual environment of the workspace around the app.
fn west(root: &Path, find: &dyn Fn(&str) -> bool) -> Result<String, Need> {
    if find("west") {
        return Ok("west".into());
    }
    root.ancestors().map(|d| d.join(".venv/bin/west")).find(|p| p.is_file()).map(|p| shell_quote(&p.to_string_lossy())).ok_or_else(|| need_tool("west"))
}

/// The Pico SDK, when the environment doesn't say where it is.
fn pico_sdk_path() -> Option<PathBuf> {
    if std::env::var_os("PICO_SDK_PATH").is_some_and(|v| !v.is_empty()) {
        return None;
    }
    let home = dirs::home_dir()?;
    for d in [home.join("pico-sdk"), home.join("pico/pico-sdk")] {
        if d.join("pico_sdk_init.cmake").is_file() {
            return Some(d);
        }
    }
    // Where the Raspberry Pi extension for VS Code installs it, one folder per version.
    let mut versions: Vec<PathBuf> = std::fs::read_dir(home.join(".pico-sdk/sdk")).ok()?.flatten().map(|e| e.path()).filter(|p| p.join("pico_sdk_init.cmake").is_file()).collect();
    versions.sort();
    versions.pop()
}

/// A drive a board shows while in its UF2 bootloader.
pub fn uf2_drive() -> Option<PathBuf> {
    let user = std::env::var("USER").unwrap_or_default();
    for base in [PathBuf::from("/run/media").join(&user), PathBuf::from("/media").join(&user), PathBuf::from("/media")] {
        for e in std::fs::read_dir(&base).into_iter().flatten().flatten() {
            if e.path().join("INFO_UF2.TXT").is_file() {
                return Some(e.path());
            }
        }
    }
    None
}

/// The firmware a command flashes: a file, or the newest `.elf` in these folders when the
/// command runs, for a build that hasn't made it yet.
#[derive(Debug, Clone)]
enum Elf {
    Path(PathBuf),
    Newest(Vec<String>),
}

impl Elf {
    /// As a shell word, or the same file with another extension (the .uf2 or .bin beside it).
    fn word(&self, ext: Option<&str>) -> String {
        match (self, ext) {
            (Elf::Path(p), None) => q(p),
            (Elf::Path(p), Some(e)) => q(&p.with_extension(e)),
            (Elf::Newest(dirs), ext) => {
                let swap = ext.map(|e| format!(" | sed 's/\\.elf$/.{e}/'")).unwrap_or_default();
                format!("\"$(ls -t $(find {} -maxdepth 3 -name '*.elf' 2>/dev/null) 2>/dev/null | head -n 1{swap})\"", dirs.join(" "))
            }
        }
    }

    /// Whether the file with that extension is there, as far as can be told now.
    fn has(&self, ext: &str) -> bool {
        match self {
            Elf::Path(p) => p.with_extension(ext).is_file(),
            // A build that makes ELFs for the Pico makes the .uf2 beside them.
            Elf::Newest(_) => true,
        }
    }
}

fn q(p: &Path) -> String {
    shell_quote(&p.to_string_lossy())
}

/// How the debugger reaches the chip.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DebugSetup {
    /// `probe-rs`, or a GDB server: `openocd`, `stlink`, `jlink`, `pyocd`.
    pub server: &'static str,
    pub chip: Option<String>,
    pub openocd: Vec<String>,
}

impl Project {
    pub fn name(&self) -> String {
        self.root.file_name().unwrap_or_default().to_string_lossy().into_owned()
    }

    /// What the status bar and the palette say about it: the kind and the board or chip.
    pub fn summary(&self) -> String {
        match self.board.as_deref().or(self.chip.as_deref()) {
            Some(b) => format!("{} · {b}", self.kind.label()),
            None => self.kind.label().to_string(),
        }
    }

    fn arduino_without_board(&self) -> bool {
        self.kind == Kind::Arduino && self.board.is_none()
    }

    fn sketch_dir(&self) -> String {
        q(&self.root)
    }

    fn fqbn(&self, pt: bool) -> Result<String, Need> {
        if self.arduino_without_board() {
            return Err(Need::Setting(if pt {
                "Escolha a placa: \"Embarcado: escolher placa…\" ou \"board\" no .tinta/embedded.json".into()
            } else {
                "Choose the board: \"Embedded: Choose Board…\", or \"board\" in .tinta/embedded.json".into()
            }));
        }
        Ok(shell_quote(self.board.as_deref().unwrap_or_default()))
    }

    fn pio_env(&self) -> String {
        self.board.as_deref().map(|e| format!(" -e {}", shell_quote(e))).unwrap_or_default()
    }

    /// The command that builds the firmware.
    pub fn build(&self, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        if let Some(b) = &self.config.build {
            return Ok(b.clone());
        }
        Ok(match self.kind {
            Kind::PlatformIO => {
                let pio = pio(find)?;
                // clangd learns the project's flags from the compilation database.
                format!("{{ [ -f compile_commands.json ] || {pio} run -t compiledb{env} >/dev/null 2>&1; }}; {pio} run{env}", env = self.pio_env())
            }
            Kind::Arduino => {
                if !find("arduino-cli") {
                    return Err(need_tool("arduino-cli"));
                }
                format!("arduino-cli compile --fqbn {} --build-path {} {}", self.fqbn(pt)?, q(&arduino_build_dir(&self.root)), self.sketch_dir())
            }
            Kind::Cargo => {
                if !find("cargo") {
                    return Err(need_tool("cargo"));
                }
                "cargo build".into()
            }
            Kind::PicoSdk => {
                if !find("cmake") {
                    return Err(need_tool("cmake"));
                }
                if !find("arm-none-eabi-gcc") {
                    return Err(need_tool("arm-none-eabi-gcc"));
                }
                let sdk = pico_sdk_path().map(|p| format!("PICO_SDK_PATH={} ", q(&p))).unwrap_or_default();
                let board = self.board.as_deref().map(|b| format!(" -DPICO_BOARD={}", shell_quote(b))).unwrap_or_default();
                format!("{sdk}cmake -S . -B build -DCMAKE_EXPORT_COMPILE_COMMANDS=ON{board} && cmake --build build -j")
            }
            Kind::EspIdf => format!("{} build", idf(find)?),
            Kind::Zephyr => {
                let west = west(&self.root, find)?;
                match &self.board {
                    Some(b) => format!("{west} build -b {}", shell_quote(b)),
                    None if self.root.join("build/zephyr").is_dir() => format!("{west} build"),
                    None => {
                        return Err(Need::Setting(if pt {
                            "Diga qual é a placa: \"board\" no .tinta/embedded.json (por exemplo, nucleo_f401re)".into()
                        } else {
                            "Say which board: \"board\" in .tinta/embedded.json (nucleo_f401re, for example)".into()
                        }));
                    }
                }
            }
            Kind::Stm32Cube | Kind::Firmware => {
                let presets = read(&self.root, "CMakePresets.json").unwrap_or_default();
                if presets.contains("\"Debug\"") {
                    if !find("cmake") {
                        return Err(need_tool("cmake"));
                    }
                    "cmake --preset Debug -DCMAKE_EXPORT_COMPILE_COMMANDS=ON && cmake --build --preset Debug".into()
                } else if ["Makefile", "makefile", "GNUmakefile"].iter().any(|m| self.root.join(m).exists()) {
                    "make -j$(nproc)".into()
                } else if self.root.join("CMakeLists.txt").exists() {
                    if !find("cmake") {
                        return Err(need_tool("cmake"));
                    }
                    "cmake -S . -B build -DCMAKE_EXPORT_COMPILE_COMMANDS=ON && cmake --build build -j".into()
                } else {
                    return Err(Need::Setting(if pt {
                        "Este projeto não tem Makefile nem CMake: no STM32CubeMX, gere o código com \"Toolchain\" Makefile ou CMake, ou diga como compilar em \"build\" no .tinta/embedded.json".into()
                    } else {
                        "This project has no Makefile or CMake: in STM32CubeMX, generate the code with the Makefile or CMake toolchain, or say how to build it in \"build\" in .tinta/embedded.json".into()
                    }));
                }
            }
        })
    }

    /// The firmware the build made.
    pub fn firmware(&self) -> Option<PathBuf> {
        if let Some(f) = &self.config.firmware {
            let f = PathBuf::from(f.replace("${workspaceFolder}", &self.root.to_string_lossy()));
            return Some(if f.is_relative() { self.root.join(f) } else { f });
        }
        let r = &self.root;
        match self.kind {
            Kind::PlatformIO => {
                let env = self.board.clone().unwrap_or_default();
                let f = r.join(".pio/build").join(&env).join("firmware.elf");
                if f.is_file() { Some(f) } else { newest_elf(&[r.join(".pio/build")], 1, false) }
            }
            Kind::Arduino => newest_elf(&[arduino_build_dir(r)], 0, false),
            Kind::Cargo => {
                let base = match &self.target {
                    Some(t) => r.join("target").join(t).join("debug"),
                    None => r.join("target/debug"),
                };
                let named = read(r, "Cargo.toml").and_then(|s| cargo_package_name(&s)).map(|n| base.join(n)).filter(|p| is_elf(p));
                named.or_else(|| newest_elf(&[base], 0, true))
            }
            Kind::Zephyr => Some(r.join("build/zephyr/zephyr.elf")).filter(|p| p.is_file()),
            Kind::PicoSdk | Kind::EspIdf => newest_elf(&[r.join("build")], 1, false),
            Kind::Stm32Cube | Kind::Firmware => newest_elf(&[r.join("build"), r.join("Debug"), r.join("Release"), r.join("out"), r.join("bin"), r.clone()], 2, false),
        }
    }

    fn openocd_files(&self) -> Vec<String> {
        if !self.openocd.is_empty() {
            return self.openocd.clone();
        }
        if self.kind == Kind::PlatformIO
            && let Some(info) = self.pio_board.as_deref().and_then(pio_board_info)
            && let Some(t) = info.openocd_target
        {
            let tool = self.debug_tool.clone().or(info.default_tool).unwrap_or_else(|| "stlink".into());
            let iface = match tool.as_str() {
                "jlink" => "jlink",
                "cmsis-dap" | "picoprobe" => "cmsis-dap",
                "raspberrypi-swd" => "raspberrypi-swd",
                _ => "stlink",
            };
            return vec![format!("interface/{iface}.cfg"), format!("target/{t}.cfg")];
        }
        match self.chip.as_deref() {
            Some(c) if c.eq_ignore_ascii_case("RP2040") => vec!["interface/cmsis-dap.cfg".into(), "target/rp2040.cfg".into()],
            Some(c) if c.eq_ignore_ascii_case("RP2350") => vec!["interface/cmsis-dap.cfg".into(), "target/rp2350.cfg".into()],
            Some(c) => stm32_openocd_target(c).map(|t| vec!["interface/stlink.cfg".into(), t]).unwrap_or_default(),
            None => Vec::new(),
        }
    }

    /// The chip, also from PlatformIO's board definition.
    pub fn chip(&self) -> Option<String> {
        if let Some(c) = &self.chip {
            return Some(c.clone());
        }
        let info = pio_board_info(self.pio_board.as_deref()?)?;
        info.jlink_device.or_else(|| {
            let mcu = info.mcu?;
            Some(if mcu.to_ascii_lowercase().starts_with("stm32") { stm32_part(&mcu) } else { mcu.to_ascii_uppercase() })
        })
    }

    fn openocd_args(files: &[String]) -> String {
        files.iter().map(|f| format!("-f {}", shell_quote(f))).collect::<Vec<_>>().join(" ")
    }

    fn usable(&self, probe: Probe, find: &dyn Fn(&str) -> bool, chip: Option<&str>) -> bool {
        match probe {
            Probe::ProbeRs => find("probe-rs") && chip.is_some(),
            Probe::OpenOcd => find("openocd") && !self.openocd_files().is_empty(),
            Probe::StLink => find("st-flash") && find("arm-none-eabi-objcopy") && is_stm32(chip),
            Probe::Stm32Programmer => find("STM32_Programmer_CLI") && is_stm32(chip),
            Probe::JLink => find("JLinkExe") && chip.is_some(),
            Probe::PyOcd => find("pyocd") && chip.is_some(),
            Probe::Picotool => find("picotool"),
            Probe::Uf2 => uf2_drive().is_some(),
        }
    }

    fn no_chip(pt: bool) -> Need {
        Need::Setting(if pt {
            "Diga qual é o chip: \"chip\" no .tinta/embedded.json (por exemplo, STM32F103C8), ou como gravar: \"probe\" e \"openocd\"".into()
        } else {
            "Say which chip it is: \"chip\" in .tinta/embedded.json (STM32F103C8, for example), or how to flash it: \"probe\" and \"openocd\"".into()
        })
    }

    /// The command that puts this ELF on the board through a probe or the board's bootloader.
    pub fn flash_elf(&self, elf: &Path, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        self.flash_with(&Elf::Path(elf.to_path_buf()), find, pt)
    }

    fn flash_with(&self, elf: &Elf, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        let chip = self.chip();
        let probe = match self.probe {
            Some(p) if p == Probe::Uf2 || find(p.tool()) => p,
            Some(p) => return Err(need_tool(p.tool())),
            None => {
                let order: &[Probe] = if self.kind == Kind::PicoSdk || chip.as_deref().is_some_and(|c| c.starts_with("RP2")) && self.kind != Kind::Cargo {
                    &[Probe::Picotool, Probe::Uf2, Probe::ProbeRs, Probe::OpenOcd]
                } else {
                    &[Probe::ProbeRs, Probe::Stm32Programmer, Probe::OpenOcd, Probe::StLink, Probe::PyOcd, Probe::JLink]
                };
                match order.iter().find(|p| self.usable(**p, find, chip.as_deref())) {
                    Some(p) => *p,
                    None if order[0] == Probe::Picotool => return Err(need_tool("picotool")),
                    None if chip.is_none() && self.openocd_files().is_empty() => return Err(Self::no_chip(pt)),
                    None => return Err(need_tool(if is_stm32(chip.as_deref()) && !find("probe-rs") { "openocd" } else { "probe-rs" })),
                }
            }
        };
        let e = elf.word(None);
        let chip_arg = || chip.as_deref().map(shell_quote).ok_or_else(|| Self::no_chip(pt));
        Ok(match probe {
            Probe::ProbeRs => {
                let c = chip_arg()?;
                format!("probe-rs download --chip {c} {e} && probe-rs reset --chip {c}")
            }
            Probe::OpenOcd => {
                let files = self.openocd_files();
                if files.is_empty() {
                    return Err(Self::no_chip(pt));
                }
                let program = match elf {
                    Elf::Path(p) => shell_quote(&format!("program {} verify reset exit", p.to_string_lossy().replace(' ', "\\ "))),
                    Elf::Newest(_) => format!("\"program {e} verify reset exit\""),
                };
                format!("openocd {} -c {program}", Self::openocd_args(&files))
            }
            Probe::StLink => {
                format!("arm-none-eabi-objcopy -O binary {e} {b} && st-flash --reset write {b} 0x08000000", b = elf.word(Some("bin")))
            }
            Probe::Stm32Programmer => format!("STM32_Programmer_CLI -c port=SWD -w {e} -v -rst"),
            Probe::JLink => {
                let c = chip_arg()?;
                format!("printf 'r\\nh\\nloadfile %s\\nr\\ng\\nqc\\n' {e} | JLinkExe -device {c} -if SWD -speed 4000 -autoconnect 1 -NoGui 1 -ExitOnError 1")
            }
            Probe::PyOcd => format!("pyocd flash -t {} {e}", chip_arg()?.to_ascii_lowercase()),
            Probe::Picotool => {
                let file = if elf.has("uf2") { elf.word(Some("uf2")) } else { e };
                // -f reboots a running Pico into its bootloader first; -x starts the program after.
                format!("picotool load -f -x {file}")
            }
            Probe::Uf2 => {
                let drive = uf2_drive().ok_or_else(|| {
                    Need::Setting(if pt {
                        "Segure o BOOTSEL e ligue a placa no USB: ela aparece como um disco".into()
                    } else {
                        "Hold BOOTSEL and plug the board in: it shows up as a drive".into()
                    })
                })?;
                format!("cp {} {}/ && sync", elf.word(Some("uf2")), q(&drive))
            }
        })
    }

    /// The command that puts the firmware, already built, on the board.
    pub fn upload(&self, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        if let Some(f) = &self.config.flash {
            return Ok(f.clone());
        }
        let port = |flag: &str| self.port.as_deref().map(|p| format!(" {flag} {}", shell_quote(p))).unwrap_or_default();
        match self.kind {
            Kind::PlatformIO => Ok(format!("{} run{} -t nobuild -t upload{}", pio(find)?, self.pio_env(), port("--upload-port"))),
            Kind::Arduino => {
                if !find("arduino-cli") {
                    return Err(need_tool("arduino-cli"));
                }
                // Without a port chosen, the first one plugged in when the upload starts.
                let port = match &self.port {
                    Some(p) => shell_quote(p),
                    None => FIRST_PORT.to_string(),
                };
                let check = if self.port.is_none() { format!("[ -n {port} ] || {{ echo {} >&2; exit 1; }} && ", shell_quote(no_port_text(pt))) } else { String::new() };
                Ok(format!("{check}arduino-cli upload -p {port} --fqbn {} --input-dir {} {}", self.fqbn(pt)?, q(&arduino_build_dir(&self.root)), self.sketch_dir()))
            }
            Kind::EspIdf => Ok(format!("{}{} flash", idf(find)?, port("-p"))),
            Kind::Zephyr => Ok(format!("{} flash", west(&self.root, find)?)),
            Kind::Cargo if self.root.join("Embed.toml").exists() && find("cargo-embed") => Ok("cargo embed".into()),
            Kind::Cargo if self.runner.is_some() && self.chip.is_none() => Ok("cargo run".into()),
            _ => self.flash_with(&self.expected_firmware(), find, pt),
        }
    }

    /// The firmware, or where the build will put it: it may not have run yet.
    fn expected_firmware(&self) -> Elf {
        if let Some(f) = self.firmware() {
            return Elf::Path(f);
        }
        let r = &self.root;
        let cmake = read(r, "CMakeLists.txt").unwrap_or_default();
        let guess = match self.kind {
            Kind::PlatformIO => Some(r.join(".pio/build").join(self.board.clone().unwrap_or_default()).join("firmware.elf")),
            Kind::Cargo => read(r, "Cargo.toml").and_then(|s| cargo_package_name(&s)).map(|n| match &self.target {
                Some(t) => r.join("target").join(t).join("debug").join(n),
                None => r.join("target/debug").join(n),
            }),
            Kind::Zephyr => Some(r.join("build/zephyr/zephyr.elf")),
            Kind::PicoSdk => cmake_call(&cmake, "add_executable").map(|n| r.join("build").join(format!("{n}.elf"))),
            _ => None,
        };
        match guess {
            Some(p) => Elf::Path(p),
            None => Elf::Newest(vec!["build".into(), "Debug".into(), "out".into(), ".".into()]),
        }
    }

    /// What Ctrl+F5 runs in a terminal once the build is done: the firmware onto the board, and
    /// then what the board says.
    pub fn run_after_build(&self, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        if self.config.flash.is_none() {
            match self.kind {
                // The runner flashes, and shows the board's log (probe-rs run, espflash --monitor).
                Kind::Cargo if self.runner.is_some() => return Ok("cargo run".into()),
                Kind::EspIdf if self.config.monitor.is_none() => {
                    let port = self.port.as_deref().map(|p| format!(" -p {}", shell_quote(p))).unwrap_or_default();
                    return Ok(format!("{}{port} flash monitor", idf(find)?));
                }
                _ => {}
            }
        }
        let upload = self.upload(find, pt)?;
        let monitor = self.monitor(find, pt)?;
        Ok(format!("{upload} && {monitor}"))
    }

    /// A terminal command that shows what the board writes to the serial port, and sends it what's
    /// typed.
    pub fn monitor(&self, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<String, Need> {
        if let Some(m) = &self.config.monitor {
            return Ok(m.clone());
        }
        let port = |flag: &str| self.port.as_deref().map(|p| format!(" {flag} {}", shell_quote(p))).unwrap_or_default();
        Ok(match self.kind {
            Kind::PlatformIO => format!("{} device monitor{}{} -b {}", pio(find)?, self.pio_env(), port("-p"), self.baud),
            // It decodes the addresses in a crash into functions and lines.
            Kind::EspIdf => format!("{}{} monitor", idf(find)?, port("-p")),
            _ => serial_monitor(self.port.as_deref(), self.baud, pt),
        })
    }

    /// Whether what the board says is best watched in the editor's serial monitor: not when the
    /// project shows it its own way (a Cargo runner like probe-rs shows the RTT log, ESP-IDF's
    /// monitor decodes crashes, or the project names its own monitor).
    pub fn uses_serial_monitor(&self) -> bool {
        self.config.monitor.is_none() && !(self.kind == Kind::Cargo && self.runner.is_some()) && self.kind != Kind::EspIdf
    }

    pub fn clean(&self, find: &dyn Fn(&str) -> bool) -> Option<String> {
        if let Some(c) = &self.config.clean {
            return Some(c.clone());
        }
        match self.kind {
            Kind::PlatformIO => pio(find).ok().map(|p| format!("{p} run{} -t clean", self.pio_env())),
            Kind::Arduino => Some(format!("rm -rf {}", q(&arduino_build_dir(&self.root)))),
            Kind::Cargo => Some("cargo clean".into()),
            Kind::EspIdf => idf(find).ok().map(|i| format!("{i} fullclean")),
            Kind::Zephyr => west(&self.root, find).ok().map(|w| format!("{w} build -t pristine")),
            Kind::PicoSdk => Some("cmake --build build --target clean".into()),
            Kind::Stm32Cube | Kind::Firmware => {
                if read(&self.root, "CMakePresets.json").is_some_and(|s| s.contains("\"Debug\"")) {
                    Some("cmake --build --preset Debug --target clean".into())
                } else if ["Makefile", "makefile", "GNUmakefile"].iter().any(|m| self.root.join(m).exists()) {
                    Some("make clean".into())
                } else {
                    None
                }
            }
        }
    }

    /// Erases the chip's whole flash.
    pub fn erase(&self, find: &dyn Fn(&str) -> bool) -> Option<String> {
        if self.kind == Kind::EspIdf {
            return idf(find).ok().map(|i| format!("{i} erase-flash"));
        }
        let chip = self.chip();
        let c = chip.as_deref().map(shell_quote);
        if find("probe-rs") && let Some(c) = &c {
            return Some(format!("probe-rs erase --chip {c}"));
        }
        if is_stm32(chip.as_deref()) {
            if find("STM32_Programmer_CLI") {
                return Some("STM32_Programmer_CLI -c port=SWD -e all".into());
            }
            if find("st-flash") {
                return Some("st-flash erase".into());
            }
        }
        if self.kind == Kind::PicoSdk && find("picotool") {
            return Some("picotool erase -f".into());
        }
        None
    }

    /// The tasks the project offers, for the task list and Ctrl+Shift+B.
    pub fn tasks(&self, find: &dyn Fn(&str) -> bool) -> Vec<Task> {
        let label = self.kind.label();
        let task = |verb: &str, command: String, group: &str| Task { name: format!("{label}: {verb}"), command, cwd: None, group: group.into() };
        let mut out = Vec::new();
        let build = self.build(find, false).ok();
        if let Some(b) = &build {
            out.push(task("build", b.clone(), "build"));
        }
        let upload = match self.kind {
            Kind::PlatformIO if self.config.flash.is_none() => pio(find).ok().map(|p| {
                let port = self.port.as_deref().map(|p| format!(" --upload-port {}", shell_quote(p))).unwrap_or_default();
                format!("{p} run{} -t upload{port}", self.pio_env())
            }),
            // These build before flashing on their own.
            Kind::EspIdf | Kind::Zephyr if self.config.flash.is_none() => self.upload(find, false).ok(),
            _ => match (&build, self.upload(find, false)) {
                (Some(b), Ok(u)) => Some(format!("{b} && {u}")),
                _ => None,
            },
        };
        if let Some(u) = upload {
            out.push(task("upload", u, ""));
        }
        if let Some(c) = self.clean(find) {
            out.push(task("clean", c, ""));
        }
        if let Some(e) = self.erase(find) {
            out.push(task("erase flash", e, ""));
        }
        if self.kind == Kind::PlatformIO && let Ok(p) = pio(find) {
            out.push(task("test", format!("{p} test{}", self.pio_env()), "test"));
            out.push(task("compile_commands.json", format!("{p} run -t compiledb{}", self.pio_env()), ""));
        }
        out
    }

    /// How F5 debugs this board, or why it can't.
    pub fn debug_setup(&self, find: &dyn Fn(&str) -> bool, pt: bool) -> Result<DebugSetup, Need> {
        let chip = self.chip();
        let setup = |server: &'static str| DebugSetup { server, chip: chip.clone(), openocd: self.openocd_files() };
        let explicit = match self.probe {
            Some(Probe::ProbeRs) => Some(("probe-rs", "probe-rs")),
            Some(Probe::OpenOcd) => Some(("openocd", "openocd")),
            Some(Probe::StLink) => Some(("stlink", "st-util")),
            Some(Probe::JLink) => Some(("jlink", "JLinkGDBServerCLExe")),
            Some(Probe::PyOcd) => Some(("pyocd", "pyocd")),
            Some(Probe::Stm32Programmer) | Some(Probe::Picotool) | Some(Probe::Uf2) => None,
            None => None,
        };
        if let Some((server, tool)) = explicit {
            if !find(tool) {
                return Err(need_tool(tool));
            }
            if server != "openocd" && server != "stlink" && chip.is_none() {
                return Err(Self::no_chip(pt));
            }
            return Ok(setup(server));
        }
        if self.kind == Kind::Arduino && self.board.as_deref().is_some_and(|b| b.starts_with("arduino:avr")) {
            return Err(Need::Setting(if pt {
                "Placas AVR, como o Uno e o Nano, não têm depuração com breakpoints: use o monitor serial".into()
            } else {
                "AVR boards, like the Uno and the Nano, can't be debugged with breakpoints: use the serial monitor".into()
            }));
        }
        if matches!(self.probe, Some(Probe::Picotool | Probe::Uf2)) || self.kind == Kind::EspIdf {
            return Err(Need::Setting(if pt {
                "Depurar precisa de uma sonda (SWD ou JTAG): diga qual em \"probe\" no .tinta/embedded.json, ou use o .tinta/launch.json".into()
            } else {
                "Debugging needs a probe (SWD or JTAG): name it in \"probe\" in .tinta/embedded.json, or use .tinta/launch.json".into()
            }));
        }
        if find("probe-rs") && chip.is_some() {
            return Ok(setup("probe-rs"));
        }
        if find("openocd") && !self.openocd_files().is_empty() {
            return Ok(setup("openocd"));
        }
        if find("st-util") && is_stm32(chip.as_deref()) {
            return Ok(setup("stlink"));
        }
        if find("pyocd") && chip.is_some() {
            return Ok(setup("pyocd"));
        }
        if find("JLinkGDBServerCLExe") && chip.is_some() {
            return Ok(setup("jlink"));
        }
        if chip.is_none() && self.openocd_files().is_empty() {
            return Err(Self::no_chip(pt));
        }
        Err(need_tool(if find("openocd") || is_stm32(chip.as_deref()) && !find("probe-rs") { "openocd" } else { "probe-rs" }))
    }
}

// The serial port ---------------------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Port {
    /// The name to open: the stable one in /dev/serial/by-id when there is one.
    pub path: String,
    /// The device behind it: /dev/ttyACM0.
    pub device: String,
    /// The maker and the product, as the USB device says.
    pub description: String,
    /// The user may open it: without that, Linux wants them in a group.
    pub accessible: bool,
}

/// Lists the ports on the computer itself, also from inside a Flatpak.
const LIST_PORTS: &str = r#"for f in /dev/serial/by-id/* /dev/ttyACM* /dev/ttyUSB* /dev/ttyAMA* /dev/rfcomm*; do
  [ -e "$f" ] || continue
  r=$(readlink -f "$f"); n=${r##*/}; d=/sys/class/tty/$n/device
  man=$(cat "$d/../manufacturer" 2>/dev/null || cat "$d/../../manufacturer" 2>/dev/null)
  prod=$(cat "$d/../product" 2>/dev/null || cat "$d/../../product" 2>/dev/null)
  ok=0; [ -r "$r" ] && [ -w "$r" ] && ok=1
  printf '%s\t%s\t%s\t%s\t%s\n' "$f" "$r" "$ok" "$man" "$prod"
done"#;

pub fn parse_ports(text: &str) -> Vec<Port> {
    let mut out: Vec<Port> = Vec::new();
    for line in text.lines() {
        let mut f = line.split('\t');
        let (Some(path), Some(device)) = (f.next(), f.next()) else { continue };
        let accessible = f.next() == Some("1");
        let man = f.next().unwrap_or("").trim();
        let prod = f.next().unwrap_or("").trim();
        let description = match (man.is_empty(), prod.is_empty()) {
            (false, false) if !prod.starts_with(man) => format!("{man} {prod}"),
            (_, false) => prod.to_string(),
            (false, true) => man.to_string(),
            (true, true) => String::new(),
        };
        // The same device under its stable name and its own: the stable one, listed first, stays.
        if out.iter().any(|p| p.device == device) {
            continue;
        }
        out.push(Port { path: path.to_string(), device: device.to_string(), description, accessible });
    }
    out
}

pub fn list_ports() -> Vec<Port> {
    let out = crate::host::command("sh", ["-c", LIST_PORTS], None, &[]).stdin(std::process::Stdio::null()).stderr(std::process::Stdio::null()).output();
    out.map(|o| parse_ports(&String::from_utf8_lossy(&o.stdout))).unwrap_or_default()
}

/// What lets a user open serial ports on this system.
pub fn port_permission_command() -> String {
    let group = if crate::lsp::distro_family() == "arch" { "uucp" } else { "dialout" };
    format!("sudo usermod -aG {group} $USER")
}


pub fn tool_hint(tool: &str) -> InstallHint {
    tool_hint_for(tool, crate::lsp::distro_family())
}

pub fn tool_hint_for(tool: &str, family: &str) -> InstallHint {
    // Arch, Fedora, Debian.
    let pkgs: (Option<&str>, Option<&str>, Option<&str>) = match tool {
        "arm-none-eabi-gcc" | "arm-none-eabi-objcopy" => (
            Some("arm-none-eabi-gcc arm-none-eabi-newlib"),
            Some("arm-none-eabi-gcc-cs arm-none-eabi-gcc-cs-c++ arm-none-eabi-newlib"),
            Some("gcc-arm-none-eabi libnewlib-arm-none-eabi"),
        ),
        "openocd" => (Some("openocd"), Some("openocd"), Some("openocd")),
        "st-flash" | "st-util" => (Some("stlink"), Some("stlink"), Some("stlink-tools")),
        "picotool" => (None, Some("picotool"), Some("picotool")),
        "cmake" => (Some("cmake"), Some("cmake"), Some("cmake")),
        "tio" => (Some("tio"), Some("tio"), Some("tio")),
        "picocom" => (Some("picocom"), Some("picocom"), Some("picocom")),
        "gdb" | "gdb-multiarch" => (Some("gdb"), Some("gdb"), Some("gdb-multiarch")),
        "cargo" => (Some("rust"), Some("cargo"), Some("cargo")),
        _ => (None, None, None),
    };
    let package = match family {
        "arch" => pkgs.0.map(|p| format!("sudo pacman -S {p}")),
        "fedora" => pkgs.1.map(|p| format!("sudo dnf install {p}")),
        "debian" => pkgs.2.map(|p| format!("sudo apt install {p}")),
        _ => None,
    };
    let fallback = match tool {
        "arduino-cli" => Some("curl -fsSL https://raw.githubusercontent.com/arduino/arduino-cli/master/install.sh | BINDIR=~/.local/bin sh"),
        "pio" | "platformio" => Some("pipx install platformio"),
        "probe-rs" => Some("curl --proto '=https' --tlsv1.2 -LsSf https://github.com/probe-rs/probe-rs/releases/latest/download/probe-rs-tools-installer.sh | sh"),
        "pyocd" => Some("pipx install pyocd"),
        "west" => Some("pipx install west"),
        "cargo-embed" => Some("cargo install probe-rs-tools --locked"),
        "elf2uf2-rs" => Some("cargo install elf2uf2-rs --locked"),
        "picotool" => Some("https://github.com/raspberrypi/picotool"),
        "idf.py" => Some("https://docs.espressif.com/projects/esp-idf/en/stable/esp32/get-started/linux-macos-setup.html"),
        "STM32_Programmer_CLI" => Some("https://www.st.com/en/development-tools/stm32cubeprog.html"),
        "JLinkExe" | "JLinkGDBServerCLExe" => Some("https://www.segger.com/downloads/jlink/"),
        _ => None,
    };
    InstallHint { server: tool.to_string(), command: package.or_else(|| fallback.map(str::to_string)) }
}


/// The serial monitor: waits for the port (a board that just got its firmware may still be
/// coming back), shows what arrives, and sends each line typed when Enter is pressed. When the
/// board goes away, as it does when it resets, it waits for it to come back. Ctrl+C ends it.
/// Arguments: the port (empty: the first one to show up), the speed, then the texts it shows.
pub const MONITOR_SCRIPT: &str = r#"want=$1 b=$2
pick() {
  if [ -n "$want" ]; then [ -e "$want" ] && p=$want && return 0; return 1; fi
  for c in /dev/serial/by-id/* /dev/ttyACM* /dev/ttyUSB*; do
    [ -e "$c" ] && { p=$c; return 0; }
  done
  return 1
}
wait_port() {
  n=0
  until pick; do
    n=$((n + 1))
    [ "$1" -gt 0 ] && [ "$n" -ge "$1" ] && return 1
    sleep 0.1
  done
}
wait_port 100 || { printf '%s\n' "$4" >&2; exit 1; }
printf '\033[2m%s: %s · %s · %s\033[0m\n' "$3" "$p" "$b" "$5"
exec 3<&0
( while IFS= read -r l <&3; do printf '%s\n' "$l" > "$p" 2>/dev/null; done ) &
w=$!
trap 'kill $w 2>/dev/null; exit 0' INT TERM HUP
while :; do
  stty -F "$p" "$b" raw -echo -hupcl clocal -crtscts 2>/dev/null && cat "$p"
  printf '\r\n\033[2m%s\033[0m\n' "$6"
  sleep 0.5
  wait_port 0
done"#;

/// The command for the serial monitor above, at a port or the first one to show up.
pub fn serial_monitor(port: Option<&str>, baud: u32, pt: bool) -> String {
    let texts: [&str; 4] = if pt {
        ["Monitor serial", "Nenhuma porta serial encontrada: ligue a placa no USB", "digite uma linha e Enter para enviar · Ctrl+C sai", "Desconectada: esperando a placa voltar…"]
    } else {
        ["Serial monitor", "No serial port found: plug the board in", "type a line and press Enter to send it · Ctrl+C quits", "Disconnected: waiting for the board to come back…"]
    };
    let mut cmd = format!("sh -c {} tinta-monitor {} {baud}", shell_quote(MONITOR_SCRIPT), shell_quote(port.unwrap_or("")));
    for t in texts {
        cmd.push(' ');
        cmd.push_str(&shell_quote(t));
    }
    cmd
}

